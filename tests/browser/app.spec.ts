test('计时、刷新恢复、暂停继续和完成降级提示', async ({ page }) => {
  await page.goto('/')
  await page.getByRole('button', { name: '自定义时长' }).click()
  await page.getByRole('spinbutton', { name: '设置分' }).fill('0')
  await page.getByRole('spinbutton', { name: '设置秒' }).fill('4')
  await page.getByRole('button', { name: '保存并使用' }).click()
  await page.getByRole('button', { name: '开始专注', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停一下' })).toBeVisible()
  await page.reload()
  await expect(page.getByRole('button', { name: '暂停一下' })).toBeVisible()
  await page.getByRole('button', { name: '暂停一下' }).click()
  const paused = await page.getByRole('timer').textContent()
  await page.waitForTimeout(1200)
  await expect(page.getByRole('timer')).toHaveText(paused!)
  await page.getByRole('button', { name: '继续专注' }).click()
  await expect(page.getByText('专注完成，辛苦了！')).toBeVisible({ timeout: 7000 })
  await page.getByRole('button', { name: '重置', exact: true }).click()
  await expect(page.getByRole('timer')).toHaveText('00:04')
  await page.reload()
  await expect(page.getByRole('button', { name: '00:04', exact: true })).toBeVisible()
})
