test('悬浮窗与主页面同步控制', async ({ page, context }) => {
  await page.goto('/')
  const supported = await page.evaluate(() => 'documentPictureInPicture' in window)
  if (!supported) {
    await page.getByRole('button', { name: /桌面悬浮窗/ }).click()
    await expect(page.getByText('请使用 Chrome / Edge 116+ 打开桌面悬浮窗。')).toBeVisible()
    return
  }
  const popupPromise = context.waitForEvent('page')
  await page.getByRole('button', { name: /桌面悬浮窗/ }).click()
  const popup = await popupPromise
  await expect(popup.getByRole('timer')).toHaveText('25:00')
  await popup.getByRole('button', { name: '开始', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停一下' })).toBeVisible()
  await popup.getByRole('button', { name: '暂停', exact: true }).click()
  await expect(page.getByRole('button', { name: '继续专注' })).toBeVisible()
  await expect(popup.locator('html')).not.toHaveClass('dark')
  await page.getByRole('button', { name: '切换深色模式' }).click()
  await expect(popup.locator('html')).toHaveClass('dark')
  await popup.getByRole('button', { name: '展开语录' }).click()
  await popup.screenshot({ path: 'test-results/pip.png', animations: 'disabled' })
  const current = await popup.locator('.mini-quote').textContent()
  await popup.getByRole('button', { name: '换一句语录' }).click()
  await expect(popup.locator('.mini-quote')).not.toHaveText(current!)
  await expect(page.locator('blockquote')).toHaveText((await popup.locator('.mini-quote').textContent())!)
  await popup.close()
  await expect(page.getByRole('button', { name: /桌面悬浮窗/ })).toBeVisible()
})
