test('紧凑 PiP 图标、缩放、锁定及偏好记忆', async ({ page, context }) => {
  await page.goto('/')
  await page.evaluate(() => {
    const api = (window as unknown as { documentPictureInPicture: { requestWindow: (o: unknown) => Promise<Window> } }).documentPictureInPicture
    const original = api.requestWindow.bind(api)
    api.requestWindow = async options => {
      localStorage.setItem('test.pip.request', JSON.stringify(options))
      const pip = await original(options)
      const resize = pip.resizeTo.bind(pip)
      pip.resizeTo = (width, height) => {
        localStorage.setItem('test.pip.resize', JSON.stringify({ width, height, innerWidth: pip.innerWidth, innerHeight: pip.innerHeight, outerWidth: pip.outerWidth, outerHeight: pip.outerHeight }))
        resize(width, height)
      }
      return pip
    }
  })
  async function open() {
    const promise = context.waitForEvent('page')
    await page.getByRole('button', { name: /桌面悬浮窗/ }).click()
    return promise
  }
  let popup = await open()
  expect(await page.evaluate(() => JSON.parse(localStorage.getItem('test.pip.request')!))).toEqual({ width: 240, height: 120 })
  await expect(popup.locator('.mini-quote')).toBeHidden()
  for (const button of await popup.getByRole('button').all()) {
    await expect(button).toHaveText('')
    await expect(button).toHaveAttribute('title')
    const bounds = await button.boundingBox()
    expect(bounds!.width).toBe(30)
    expect(bounds!.height).toBe(30)
  }
  await popup.setViewportSize({ width: 240, height: 120 })
  await popup.screenshot({ path: 'test-results/pip-compact-light.png', animations: 'disabled' })
  expect(await popup.evaluate(() => document.documentElement.scrollHeight <= innerHeight && document.documentElement.scrollWidth <= innerWidth)).toBe(true)
  await popup.getByRole('button', { name: '展开语录' }).click()
  await expect(popup.locator('.mini-quote')).toBeVisible()
  const expanded = await page.evaluate(() => JSON.parse(localStorage.getItem('test.pip.resize')!))
  expect(expanded.height).toBe(170 + Math.max(0, expanded.outerHeight - expanded.innerHeight))
  await popup.setViewportSize({ width: 240, height: 170 })
  await popup.screenshot({ path: 'test-results/pip-expanded-light.png', animations: 'disabled' })
  expect(await popup.locator('.mini-quote').evaluate(el => el.getBoundingClientRect().height)).toBeLessThanOrEqual(36)
  await popup.getByRole('button', { name: '开启防误触锁' }).click()
  for (const name of ['开始', '重置', '换一句语录', '收起语录']) await expect(popup.getByRole('button', { name, exact: true })).toBeDisabled()
  await expect(page.getByRole('button', { name: '悬浮窗 · 防误触已锁定' })).toBeVisible()
  // Main-page controls remain functional while the PiP controls are locked.
  await page.getByRole('button', { name: '开始专注', exact: true }).click()
  await expect(popup.getByRole('button', { name: '暂停', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '暂停一下', exact: true }).click()
  await expect(popup.getByRole('button', { name: '继续', exact: true })).toBeDisabled()
  await page.getByRole('button', { name: '切换深色模式' }).click()
  await expect(popup.locator('html')).toHaveClass('dark')
  await popup.screenshot({ path: 'test-results/pip-locked-dark.png', animations: 'disabled' })
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('focus.pip.v1')!))).toEqual({ expanded: true, locked: true })
  await popup.close()
  await page.reload()
  const reopened = context.waitForEvent('page')
  await page.getByRole('button', { name: /桌面悬浮窗/ }).click()
  popup = await reopened
  await expect(popup.getByRole('button', { name: '解锁防误触' })).toBeVisible()
  await expect(popup.getByRole('button', { name: '继续', exact: true })).toBeDisabled()
  await expect(popup.locator('.mini-quote')).toBeVisible()
  await popup.getByRole('button', { name: '解锁防误触' }).click()
  await expect(popup.getByRole('button', { name: '继续', exact: true })).toBeEnabled()
  await popup.getByRole('button', { name: '继续', exact: true }).click()
  await expect(page.getByRole('button', { name: '暂停一下' })).toBeVisible()
  await popup.getByRole('button', { name: '重置', exact: true }).click()
  await expect(page.getByRole('timer')).toHaveText('25:00')
  await popup.getByRole('button', { name: '收起语录' }).click()
  await expect(popup.locator('.mini-quote')).toBeHidden()
  await expect.poll(() => page.evaluate(() => JSON.parse(localStorage.getItem('focus.pip.v1')!))).toEqual({ expanded: false, locked: false })
  await popup.close()
})
