import { test, expect } from '@playwright/test'

test('命令面板复用计时操作，运行时禁用时长选择', async ({ page }) => {
  const errors: string[] = []
  page.on('pageerror', error => errors.push(error.message))
  await page.goto('/')
  await page.keyboard.press('Control+k')
  await expect(page.getByRole('dialog', { name: '专注快捷操作' })).toBeVisible()
  await page.getByPlaceholder('想做什么？搜索时间、语录、主题…').fill('15 分钟')
  await page.keyboard.press('Enter')
  await expect(page.getByRole('timer')).toHaveText('15:00')
  await page.getByRole('button', { name: '打开命令面板' }).click()
  await page.getByRole('option', { name: '开始专注' }).click()
  await expect(page.getByRole('button', { name: '暂停一下' })).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-phase', 'focus')
  await page.keyboard.press('Control+k')
  await expect(page.getByRole('option', { name: '5 分钟专注', exact: true })).toHaveAttribute('aria-disabled', 'true')
  await page.getByRole('option', { name: '暂停专注' }).click()
  await expect(page.locator('html')).toHaveAttribute('data-phase', 'paused')
  await page.keyboard.press('Control+k')
  await page.getByRole('option', { name: '重置本轮计时' }).click()
  await expect(page.getByRole('timer')).toHaveText('15:00')
  await page.keyboard.press('Control+k')
  await page.getByRole('option', { name: '自定义时长' }).click()
  await expect(page.getByRole('dialog', { name: '留给自己多少时间？' })).toBeVisible()
  await page.getByRole('slider').focus()
  await page.keyboard.press('ArrowRight')
  await expect(page.getByRole('spinbutton', { name: '设置分' })).toHaveValue('16')
  await page.getByRole('button', { name: '仅使用本次' }).click()
  await expect(page.getByRole('timer')).toHaveText('16:00')
  expect(errors).toEqual([])
})

test('动效可热切换，页面隐藏时停止绘制且不影响计时', async ({ page }) => {
  await page.emulateMedia({ reducedMotion: 'no-preference' })
  await page.goto('/')
  const canvas = page.locator('.particle-ring')
  await expect(canvas).toHaveAttribute('data-active', 'true')
  await page.setViewportSize({ width: 1440, height: 1080 })
  await page.screenshot({ path: 'test-results/redesign-particles.png', fullPage: true, animations: 'disabled' })
  await page.getByRole('button', { name: '开始专注', exact: true }).click()
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: true })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(canvas).toHaveAttribute('data-active', 'false')
  await page.evaluate(() => {
    Object.defineProperty(document, 'hidden', { configurable: true, value: false })
    document.dispatchEvent(new Event('visibilitychange'))
  })
  await expect(canvas).toHaveAttribute('data-active', 'true')
  await page.emulateMedia({ reducedMotion: 'reduce' })
  await expect(canvas).toHaveAttribute('data-active', 'false')
  await expect(canvas).toBeHidden()
  await page.getByRole('button', { name: '暂停一下' }).click()
  await expect(page.getByRole('button', { name: '继续专注' })).toBeVisible()
})

test('Canvas 失败仍能完成计时并保留 DOM 数字与基础圆环', async ({ page }) => {
  await page.addInitScript(() => {
    HTMLCanvasElement.prototype.getContext = () => { throw new Error('Canvas disabled') }
    Object.defineProperty(window, 'AudioContext', { value: class { constructor() { throw new Error('Audio disabled') } } })
  })
  await page.goto('/')
  await page.getByRole('button', { name: '自定义时长' }).click()
  await page.getByRole('spinbutton', { name: '设置分' }).fill('0')
  await page.getByRole('spinbutton', { name: '设置秒' }).fill('1')
  await page.getByRole('button', { name: '仅使用本次' }).click()
  await page.getByRole('button', { name: '开始专注', exact: true }).click()
  await expect(page.getByText('专注完成，辛苦了！')).toBeVisible()
  await expect(page.getByRole('timer')).toHaveText('00:00')
  await expect(page.locator('.ring-value')).toBeVisible()
  await expect(page.locator('html')).toHaveAttribute('data-phase', 'done')
})

